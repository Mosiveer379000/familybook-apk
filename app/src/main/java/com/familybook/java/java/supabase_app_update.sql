-- GitHub Actions (release.yml) প্রতি build-এ এই টেবিলে নতুন সারি বসায়; অ্যাপ সর্বশেষ version_code-টা পড়ে।

create table if not exists public.app_updates (
  id           bigint generated by default as identity primary key,
  version_code bigint not null default 0,
  version_name text,
  apk_url      text,
  whats_new    text,
  created_at   timestamptz not null default now()
);

-- আগের টেবিলে না থাকলে কলামগুলো যোগ হবে
alter table public.app_updates add column if not exists version_name     text;
alter table public.app_updates add column if not exists apk_url          text;
alter table public.app_updates add column if not exists whats_new        text;
alter table public.app_updates add column if not exists min_version_code bigint  not null default 0; -- এর চেয়ে পুরনো ভার্সনে আপডেট বাধ্যতামূলক
alter table public.app_updates add column if not exists force            boolean not null default false; -- true হলে Later বাটন থাকবে না

-- অ্যাপ (anon) শুধু পড়তে পারবে; লিখতে পারবে শুধু GitHub Actions (service_role key)
alter table public.app_updates enable row level security;
drop policy if exists "app_updates_read" on public.app_updates;
create policy "app_updates_read" on public.app_updates for select using (true);
